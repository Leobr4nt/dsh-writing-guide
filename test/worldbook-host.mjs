import assert from 'node:assert/strict';
import { createTavernHost } from '../lib/tavern-host.js';
import { createTavernEvents } from '../lib/tavern-events.js';
const entry={uid:5,comment:'Fixture',content:'synthetic',disable:false,constant:false,vectorized:false,key:['one'],keysecondary:['two'],selectiveLogic:3,scanDepth:8,position:6,role:2,depth:9,order:17,useProbability:true,probability:45,excludeRecursion:true,preventRecursion:true,delayUntilRecursion:2,sticky:3,cooldown:4,delay:5,extra:{fixture:true},unknown:'keep'};
const original=structuredClone(entry);
const host=createTavernHost({worlds:[{id:'w',name:'Fixture',entries:[entry]}]},createTavernEvents());
const api=host.apiFor('fixture');
const before=await api.getWorldbook('Fixture');
assert.equal(before[0].strategy.keys_secondary.logic,'and_all');
assert.equal(before[0].position.type,'after_example_messages');
await api.replaceWorldbook('Fixture',before);
assert.deepEqual(await api.getWorldbook('Fixture'),before,'read/replace preserves public worldbook fields');
assert.equal(host.state.worlds[0].entries[0].unknown,'keep');
await api.updateWorldbookWith('Fixture',rows=>rows.map(row=>({...row,strategy:{...row.strategy,keys_secondary:{logic:'not_any',keys:['new']}},position:{type:'outlet',role:'user',depth:2,order:31},effect:{sticky:null,cooldown:9,delay:null},recursion:{prevent_incoming:false,prevent_outgoing:true,delay_until:4}})));
const updated=host.state.worlds[0].entries[0];
assert.equal(updated.selectiveLogic,2);assert.equal(updated.position,7);assert.equal(updated.role,1);assert.equal(updated.depth,2);assert.equal(updated.order,31);assert.equal(updated.cooldown,9);assert.equal(updated.delayUntilRecursion,4);
await assert.rejects(api.getWorldbook('missing'),/WORLD_NOT_FOUND/);
assert.equal(await host.silly.loadWorldInfo('missing'),null);
assert.deepEqual(entry,original,'caller material is detached from runtime writes');
console.log('worldbook-host: entry roundtrip, positions, recursion and effect updates passed');
